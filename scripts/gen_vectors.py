#!/usr/bin/env python3
"""Generate the AES-128 test vectors used by the testbench: vectors/aes128_vectors.txt

Each line: key plaintext ciphertext (32 hexadecimal digits each, ECB, one block).
The expected ciphertexts come from OpenSSL (through the Python 'cryptography' package), which is independent
from the VHDL code. The two examples of FIPS 197 are checked against the values printed in the standard.

Usage: python3 scripts/gen_vectors.py
"""
import random
from pathlib import Path

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

FIPS197 = [
    # appendix B
    ("2b7e151628aed2a6abf7158809cf4f3c", "3243f6a8885a308d313198a2e0370734", "3925841d02dc09fbdc118597196a0b32"),
    # appendix C.1
    ("000102030405060708090a0b0c0d0e0f", "00112233445566778899aabbccddeeff", "69c4e0d86a7b0430d8cdb78070b4c55a"),
]


def encrypt(key_hex, pt_hex):
    enc = Cipher(algorithms.AES(bytes.fromhex(key_hex)), modes.ECB()).encryptor()
    return (enc.update(bytes.fromhex(pt_hex)) + enc.finalize()).hex()


def main():
    lines = []
    for k, p, c in FIPS197:
        assert encrypt(k, p) == c, "OpenSSL disagrees with FIPS 197"
        lines.append((k, p, c))

    zero, ones = "00" * 16, "ff" * 16
    cases = [(zero, zero), (ones, ones), (zero, ones), (ones, zero)]
    for bit in range(128):                                   # one bit set in the plaintext
        cases.append((zero, "%032x" % (1 << bit)))
    for bit in range(128):                                   # one bit set in the key
        cases.append(("%032x" % (1 << bit), zero))
    rng = random.Random(2026)
    for _ in range(500):                                     # random cases, fixed seed
        cases.append(("%032x" % rng.getrandbits(128), "%032x" % rng.getrandbits(128)))
    for k, p in cases:
        lines.append((k, p, encrypt(k, p)))

    out = Path(__file__).resolve().parent.parent / "vectors" / "aes128_vectors.txt"
    with open(out, "w") as f:
        f.write("# key plaintext ciphertext (AES-128, ECB). Generated by scripts/gen_vectors.py\n")
        f.write("# The first two lines are the examples of FIPS 197 (appendix B and C.1).\n")
        for k, p, c in lines:
            f.write("%s %s %s\n" % (k, p, c))
    print("wrote %d vectors to %s" % (len(lines), out))


if __name__ == "__main__":
    main()
